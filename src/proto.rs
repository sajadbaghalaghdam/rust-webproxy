//! Wire format shared by client and server.
//!
//! Every tunnel exchange is a single outer `POST <tunnel_path>` whose body starts with
//! `[VERSION, message type]`:
//!
//! * `MSG_HELLO` – key exchange (see `crypto`), answered with `MSG_HELLO_OK`.
//! * `MSG_DATA`  – `[session id (16)] [request seq (8)]` followed by encrypted frames:
//!   frame 0 is the encoded [`RequestHead`], the rest carry the request body. The final frame
//!   has the LAST flag set, always carries the last body bytes and, in requests, ends with an
//!   8-byte age stamp (see `body::SealBody`). The answer is `[VERSION, MSG_DATA_OK]` followed by
//!   frames in the same layout carrying a [`ResponseHead`] and the response body; before its
//!   head the server may send keep-alive headers (`0u32`) while the destination is working.
//!
//! A frame is a `u32` big-endian header (bit 31 = LAST, bits 0..31 = ciphertext length
//! including the tag) followed by the ChaCha20-Poly1305 ciphertext.

use std::fmt::{self, Write as _};

use bytes::{Buf, BufMut, Bytes, BytesMut};
use http::header::{self, HeaderMap, HeaderName, HeaderValue};
use http::{Method, StatusCode, Uri};

pub type BoxError = Box<dyn std::error::Error + Send + Sync>;

pub const VERSION: u8 = 2;
pub const MSG_HELLO: u8 = 0x01;
pub const MSG_HELLO_OK: u8 = 0x81;
pub const MSG_DATA: u8 = 0x02;
pub const MSG_DATA_OK: u8 = 0x82;

pub const SESSION_ID_LEN: usize = 16;
pub type SessionId = [u8; SESSION_ID_LEN];
pub const KEY_HINT_LEN: usize = 8;
/// `[version, type, session id, request seq]`
pub const DATA_PREFIX_LEN: usize = 2 + SESSION_ID_LEN + 8;

/// Maximum plaintext carried by one body frame.
pub const FRAME_SIZE: usize = 32 * 1024;
/// Maximum size of an encoded request/response head (it travels in a single frame).
pub const MAX_HEAD_LEN: usize = 256 * 1024;
const MAX_HEADERS: usize = 1024;

/// Padding granularity of encoded heads: hides exact URL / header lengths from the CDN.
const HEAD_PAD: usize = 256;

/// Header a local application sets to choose the destination: a base URL to which the
/// request's own path and query are appended.
pub const TARGET_HEADER: &str = "x-tunnel-target";
/// Header carrying the exact destination URL (path and query included); the local request's
/// path is ignored.
pub const URL_HEADER: &str = "x-tunnel-url";
/// Marks responses generated by webproxy itself rather than by the destination.
pub const ERROR_HEADER: &str = "x-webproxy-error";

/// Protocol, framing or authentication failure.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ProtoError(pub &'static str);

impl fmt::Display for ProtoError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.0)
    }
}

impl std::error::Error for ProtoError {}

/// Head encoding failures caused by an oversized request/response head.
pub const HEAD_TOO_LARGE: ProtoError = ProtoError("message head too large");
pub const TOO_MANY_HEADERS: ProtoError = ProtoError("too many headers");
pub const HEADER_TOO_LARGE: ProtoError = ProtoError("header too large");

impl ProtoError {
    /// True for errors caused by the size of a head rather than by its contents.
    pub fn is_size_limit(self) -> bool {
        [HEAD_TOO_LARGE, TOO_MANY_HEADERS, HEADER_TOO_LARGE].iter().any(|e| e.0 == self.0)
    }
}

/// A message head that is serialized straight into an output buffer.
pub trait EncodeHead {
    fn encode_into(&self, buf: &mut BytesMut) -> Result<(), ProtoError>;
}

#[derive(Debug)]
pub struct RequestHead {
    pub method: Method,
    /// Absolute destination URL (`http://` or `https://`).
    pub uri: Uri,
    /// Exact body length when known up front.
    pub body_len: Option<u64>,
    pub headers: HeaderMap,
}

#[derive(Debug)]
pub struct ResponseHead {
    pub status: StatusCode,
    pub body_len: Option<u64>,
    pub headers: HeaderMap,
}

impl EncodeHead for RequestHead {
    fn encode_into(&self, b: &mut BytesMut) -> Result<(), ProtoError> {
        let start = b.len();
        let method = self.method.as_str();
        let method_len = u8::try_from(method.len()).map_err(|_| ProtoError("method too long"))?;
        b.put_u8(method_len);
        b.put_slice(method.as_bytes());
        // URI: u32 length patched after formatting it in place.
        let len_at = b.len();
        b.put_u32(0);
        write!(b, "{}", self.uri).map_err(|_| ProtoError("cannot encode target url"))?;
        let uri_len = (b.len() - len_at - 4) as u32;
        b[len_at..len_at + 4].copy_from_slice(&uri_len.to_be_bytes());
        put_opt_u64(b, self.body_len);
        put_headers(b, &self.headers)?;
        put_padding(b, start)
    }
}

impl RequestHead {
    /// Decodes a head; header values and the URI share `buf` instead of being copied.
    pub fn decode(buf: Bytes) -> Result<Self, ProtoError> {
        let mut r = Reader(buf);
        let method_len = r.u8()? as usize;
        let method = Method::from_bytes(&r.take(method_len)?).map_err(|_| ProtoError("invalid method"))?;
        let uri_len = r.u32()? as usize;
        let uri = Uri::from_maybe_shared(r.take(uri_len)?).map_err(|_| ProtoError("invalid target url"))?;
        let body_len = r.opt_u64()?;
        let headers = r.headers()?;
        r.finish()?;
        Ok(Self { method, uri, body_len, headers })
    }
}

impl EncodeHead for ResponseHead {
    fn encode_into(&self, b: &mut BytesMut) -> Result<(), ProtoError> {
        let start = b.len();
        b.put_u16(self.status.as_u16());
        put_opt_u64(b, self.body_len);
        put_headers(b, &self.headers)?;
        put_padding(b, start)
    }
}

impl ResponseHead {
    pub fn decode(buf: Bytes) -> Result<Self, ProtoError> {
        let mut r = Reader(buf);
        let status = StatusCode::from_u16(r.u16()?).map_err(|_| ProtoError("invalid status"))?;
        let body_len = r.opt_u64()?;
        let headers = r.headers()?;
        r.finish()?;
        Ok(Self { status, body_len, headers })
    }
}

/// Appends `u16 padding length | zeros` so the head length is a multiple of HEAD_PAD.
fn put_padding(b: &mut BytesMut, start: usize) -> Result<(), ProtoError> {
    let unpadded = b.len() - start + 2;
    let pad = (HEAD_PAD - unpadded % HEAD_PAD) % HEAD_PAD;
    if unpadded + pad > MAX_HEAD_LEN {
        return Err(HEAD_TOO_LARGE);
    }
    b.put_u16(pad as u16);
    b.put_bytes(0, pad);
    Ok(())
}

fn put_opt_u64(b: &mut BytesMut, v: Option<u64>) {
    match v {
        Some(n) => {
            b.put_u8(1);
            b.put_u64(n);
        }
        None => b.put_u8(0),
    }
}

fn put_headers(b: &mut BytesMut, h: &HeaderMap) -> Result<(), ProtoError> {
    if h.len() > MAX_HEADERS {
        return Err(TOO_MANY_HEADERS);
    }
    b.put_u16(h.len() as u16);
    for (name, value) in h {
        let (n, v) = (name.as_str().as_bytes(), value.as_bytes());
        if n.len() > u16::MAX as usize || v.len() > MAX_HEAD_LEN {
            return Err(HEADER_TOO_LARGE);
        }
        b.put_u16(n.len() as u16);
        b.put_slice(n);
        b.put_u32(v.len() as u32);
        b.put_slice(v);
    }
    Ok(())
}

/// Bounds-checked cursor over a decrypted head.
struct Reader(Bytes);

impl Reader {
    fn need(&self, n: usize) -> Result<(), ProtoError> {
        if self.0.len() < n {
            Err(ProtoError("truncated message head"))
        } else {
            Ok(())
        }
    }
    fn take(&mut self, n: usize) -> Result<Bytes, ProtoError> {
        self.need(n)?;
        Ok(self.0.split_to(n))
    }
    fn u8(&mut self) -> Result<u8, ProtoError> {
        self.need(1)?;
        Ok(self.0.get_u8())
    }
    fn u16(&mut self) -> Result<u16, ProtoError> {
        self.need(2)?;
        Ok(self.0.get_u16())
    }
    fn u32(&mut self) -> Result<u32, ProtoError> {
        self.need(4)?;
        Ok(self.0.get_u32())
    }
    fn opt_u64(&mut self) -> Result<Option<u64>, ProtoError> {
        match self.u8()? {
            0 => Ok(None),
            1 => {
                self.need(8)?;
                Ok(Some(self.0.get_u64()))
            }
            _ => Err(ProtoError("invalid length marker")),
        }
    }
    fn headers(&mut self) -> Result<HeaderMap, ProtoError> {
        let count = self.u16()? as usize;
        if count > MAX_HEADERS {
            return Err(ProtoError("too many headers"));
        }
        let mut h = HeaderMap::with_capacity(count);
        for _ in 0..count {
            let name_len = self.u16()? as usize;
            let name = HeaderName::from_bytes(&self.take(name_len)?).map_err(|_| ProtoError("invalid header name"))?;
            let value_len = self.u32()? as usize;
            let value =
                HeaderValue::from_maybe_shared(self.take(value_len)?).map_err(|_| ProtoError("invalid header value"))?;
            h.append(name, value);
        }
        Ok(h)
    }
    /// Skips the padding and checks that nothing else follows.
    fn finish(mut self) -> Result<(), ProtoError> {
        let pad = self.u16()? as usize;
        if self.take(pad)?.iter().any(|&b| b != 0) {
            return Err(ProtoError("invalid head padding"));
        }
        if self.0.is_empty() {
            Ok(())
        } else {
            Err(ProtoError("trailing bytes in message head"))
        }
    }
}

const HOP_BY_HOP: [HeaderName; 9] = [
    header::CONNECTION,
    HeaderName::from_static("keep-alive"),
    HeaderName::from_static("proxy-connection"),
    header::PROXY_AUTHENTICATE,
    header::PROXY_AUTHORIZATION,
    header::TE,
    header::TRAILER,
    header::TRANSFER_ENCODING,
    header::UPGRADE,
];

/// Removes connection-specific headers (RFC 9110 §7.6.1), including any listed in `Connection`.
pub fn strip_hop_by_hop(h: &mut HeaderMap) {
    let listed: Vec<HeaderName> = h
        .get_all(header::CONNECTION)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(','))
        .filter_map(|t| HeaderName::from_bytes(t.trim().as_bytes()).ok())
        .collect();
    for name in listed.iter().chain(HOP_BY_HOP.iter()) {
        h.remove(name);
    }
}

/// Formats an error together with its `source()` chain.
pub fn error_chain(e: &(dyn std::error::Error + 'static)) -> String {
    let mut s = e.to_string();
    let mut cur = e.source();
    while let Some(c) = cur {
        let cs = c.to_string();
        if !s.contains(&cs) {
            s.push_str(": ");
            s.push_str(&cs);
        }
        cur = c.source();
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn encode(h: &impl EncodeHead) -> Bytes {
        let mut b = BytesMut::new();
        h.encode_into(&mut b).unwrap();
        b.freeze()
    }

    #[test]
    fn request_head_roundtrip() {
        let mut headers = HeaderMap::new();
        headers.append("set-cookie", HeaderValue::from_static("a=1"));
        headers.append("set-cookie", HeaderValue::from_static("b=2"));
        headers.insert("x-bin", HeaderValue::from_bytes(b"\x80\xffraw").unwrap());
        let h = RequestHead {
            method: Method::from_bytes(b"PROPFIND").unwrap(),
            uri: Uri::from_static("http://127.0.0.1:3000/a/b?x=1&y=%20"),
            body_len: Some(12345),
            headers,
        };
        let d = RequestHead::decode(encode(&h)).unwrap();
        assert_eq!(d.method.as_str(), "PROPFIND");
        assert_eq!(d.uri, h.uri);
        assert_eq!(d.body_len, Some(12345));
        let cookies: Vec<_> = d.headers.get_all("set-cookie").iter().collect();
        assert_eq!(cookies, vec!["a=1", "b=2"]);
        assert_eq!(d.headers["x-bin"].as_bytes(), b"\x80\xffraw");
    }

    #[test]
    fn heads_are_padded() {
        for n in 0..40 {
            let mut headers = HeaderMap::new();
            headers.insert("x-a", HeaderValue::from_str(&"v".repeat(n * 7)).unwrap());
            let h = ResponseHead { status: StatusCode::OK, body_len: Some(1), headers };
            let enc = encode(&h);
            assert_eq!(enc.len() % HEAD_PAD, 0);
            assert_eq!(ResponseHead::decode(enc).unwrap().headers["x-a"].len(), n * 7);
        }
    }

    #[test]
    fn response_head_roundtrip() {
        let h = ResponseHead { status: StatusCode::IM_A_TEAPOT, body_len: None, headers: HeaderMap::new() };
        let d = ResponseHead::decode(encode(&h)).unwrap();
        assert_eq!(d.status, StatusCode::IM_A_TEAPOT);
        assert_eq!(d.body_len, None);
    }

    #[test]
    fn malformed_heads_error_instead_of_panicking() {
        let h = RequestHead {
            method: Method::GET,
            uri: Uri::from_static("http://x/"),
            body_len: None,
            headers: HeaderMap::new(),
        };
        let enc = encode(&h);
        for cut in 0..enc.len() {
            assert!(RequestHead::decode(enc.slice(..cut)).is_err());
        }
        let mut longer = enc.to_vec();
        longer.push(0);
        assert!(RequestHead::decode(Bytes::from(longer)).is_err());
        for seed in 0u32..2000 {
            let junk: Bytes =
                (0..(seed % 97)).map(|i| (seed.wrapping_mul(31).wrapping_add(i * 7)) as u8).collect::<Vec<_>>().into();
            let _ = RequestHead::decode(junk.clone());
            let _ = ResponseHead::decode(junk);
        }
    }

    #[test]
    fn hop_by_hop_removed() {
        let mut h = HeaderMap::new();
        h.insert("connection", HeaderValue::from_static("keep-alive, x-secret"));
        h.insert("x-secret", HeaderValue::from_static("1"));
        h.insert("transfer-encoding", HeaderValue::from_static("chunked"));
        h.insert("x-keep", HeaderValue::from_static("1"));
        strip_hop_by_hop(&mut h);
        assert_eq!(h.len(), 1);
        assert!(h.contains_key("x-keep"));
    }
}
